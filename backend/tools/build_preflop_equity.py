"""Build app/preflop_equity_data.py: exact heads-up preflop all-in equities.

Hand2Note computes heads-up preflop all-in EV from exact equities (every
possible board, ties counted half). Enumerating 1.7M boards per hand at
import time is too slow, so we enumerate every matchup once here and ship
the result as a table. Matchups are reduced by suit symmetry to 47,008.

Needs numpy (not a runtime dependency). Takes ~15 minutes on 10 cores:

    cd backend && python tools/build_preflop_equity.py
"""

import base64
import itertools
import sys
import time
import zlib
from array import array
from multiprocessing import Pool
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.equity import canonical_matchup, _encode_key  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "app" / "preflop_equity_data.py"
N_BOARDS = 1_712_304  # C(48, 5)


def _top_bits(m: int, k: int) -> int:
    out = 0
    for r in range(12, -1, -1):
        if k and m >> r & 1:
            out |= 1 << r
            k -= 1
    return out


def _straight_high(m: int) -> int:
    for hi in range(12, 3, -1):
        need = 0x1F << (hi - 4)
        if m & need == need:
            return hi + 1
    wheel = (1 << 12) | 0xF
    return 4 if m & wheel == wheel else 0


POP = np.array([bin(i).count("1") for i in range(8192)], dtype=np.int8)
HIGH = np.array([_top_bits(i, 1) for i in range(8192)], dtype=np.int32)
TOP2 = np.array([_top_bits(i, 2) for i in range(8192)], dtype=np.int32)
TOP3 = np.array([_top_bits(i, 3) for i in range(8192)], dtype=np.int32)
TOP5 = np.array([_top_bits(i, 5) for i in range(8192)], dtype=np.int32)
STRAIGHT = np.array([_straight_high(i) for i in range(8192)], dtype=np.int32)
# One bit per card in a 64-bit word: 16 bits per suit, rank bit inside it
CARDBIT = np.array([1 << ((c // 4) + 16 * (c % 4)) for c in range(52)], dtype=np.int64)
COMBOS = np.array(list(itertools.combinations(range(48), 5)), dtype=np.int8)


def _values(packed: np.ndarray) -> np.ndarray:
    """7-card hand strength (bigger is better) from per-suit rank masks."""
    s = [((packed >> (16 * i)) & 0x1FFF).astype(np.int32) for i in range(4)]
    s0, s1, s2, s3 = s
    m1 = s0 | s1 | s2 | s3                     # ranks present
    m4 = s0 & s1 & s2 & s3                     # quads
    m2 = (s0 & s1) | (s0 & s2) | (s0 & s3) | (s1 & s2) | (s1 & s3) | (s2 & s3)
    m3 = (s0 & s1 & s2) | (s0 & s1 & s3) | (s0 & s2 & s3) | (s1 & s2 & s3)
    fl = np.zeros_like(m1)
    for x in s:
        fl = np.where(POP[x] >= 5, x, fl)
    sf = STRAIGHT[fl]
    st = STRAIGHT[m1]
    t = HIGH[m3]
    fh_pair = HIGH[m2 & ~t]
    p2 = TOP2[m2]
    conds = [sf > 0, m4 > 0, (m3 > 0) & (fh_pair > 0), fl > 0, st > 0,
             m3 > 0, POP[m2] >= 2, m2 > 0]
    vals = [
        (8 << 26) | sf,
        (7 << 26) | (m4 << 13) | HIGH[m1 & ~m4],
        (6 << 26) | (t << 13) | fh_pair,
        (5 << 26) | TOP5[fl],
        (4 << 26) | st,
        (3 << 26) | (t << 13) | TOP2[m1 & ~t],
        (2 << 26) | (p2 << 13) | HIGH[m1 & ~p2],
        (1 << 26) | (m2 << 13) | TOP3[m1 & ~m2],
    ]
    return np.select(conds, vals, TOP5[m1])


def numerator(matchup) -> int:
    """2 * wins + ties of hand 1 over all 1,712,304 boards."""
    (a1, a2), (b1, b2) = matchup
    used = {a1, a2, b1, b2}
    rem = np.array([c for c in range(52) if c not in used], dtype=np.int64)
    boards = rem[COMBOS]
    packed = np.zeros(len(boards), dtype=np.int64)
    for j in range(5):
        packed |= CARDBIT[boards[:, j]]
    v1 = _values(packed | CARDBIT[a1] | CARDBIT[a2])
    v2 = _values(packed | CARDBIT[b1] | CARDBIT[b2])
    return 2 * int(np.count_nonzero(v1 > v2)) + int(np.count_nonzero(v1 == v2))


def all_matchups() -> list:
    hands = list(itertools.combinations(range(52), 2))
    seen = set()
    for i, a in enumerate(hands):
        for b in hands[i + 1:]:
            if a[0] in b or a[1] in b:
                continue
            seen.add(canonical_matchup(a, b)[0])
    return sorted(seen)


def main() -> None:
    t0 = time.time()
    matchups = all_matchups()
    print(f"{len(matchups)} matchups ({time.time() - t0:.0f}s)", flush=True)
    with Pool() as pool:
        nums = []
        for i, n in enumerate(pool.imap(numerator, matchups, chunksize=64)):
            nums.append(n)
            if i % 2000 == 0:
                print(f"{i}/{len(matchups)} ({time.time() - t0:.0f}s)", flush=True)
    keys = array("I", (_encode_key(m) for m in matchups))
    vals = array("I", nums)
    blob = base64.b64encode(zlib.compress(keys.tobytes() + vals.tobytes(), 9)).decode()
    lines = [blob[i:i + 100] for i in range(0, len(blob), 100)]
    OUT.write_text(
        '"""Generated by tools/build_preflop_equity.py. Do not edit.\n\n'
        "Exact heads-up preflop equities, one entry per suit-canonical matchup:\n"
        "zlib(keys uint32[n] + numerators uint32[n]), base64. Equity of the\n"
        f'first hand = numerator / (2 * {N_BOARDS}).\n"""\n\n'
        f"COUNT = {len(matchups)}\n"
        "DATA = (\n" + "".join(f'    "{l}"\n' for l in lines) + ")\n"
    )
    print(f"wrote {OUT} ({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
